async def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--days", type=int, default=28)
    ap.add_argument("--per-day", type=int, default=360)
    ap.add_argument("--seed", type=int, default=20260723)
    ap.add_argument("--reset", action="store_true", help="truncate calls and alerts first")
    ap.add_argument("--if-empty", action="store_true",
                    help="seed only when the calls table is empty (used by the Docker entrypoint)")
    args = ap.parse_args()

    await db.connect()
    await db.apply_schema()

    if args.if_empty:
        existing = await db.pool().fetchval("SELECT count(*) FROM calls")
        if existing:
            print(f"calls table already has {existing} rows — skipping seed")
            await db.disconnect()
            return

    if args.reset:
        async with db.pool().acquire() as conn:
            await conn.execute("TRUNCATE calls; TRUNCATE alerts;")
        print("cleared existing calls and alerts")

    print(f"generating ~{args.days} days at ~{args.per_day}/day ...")
    calls = build(args.days, args.per_day, args.seed)

    # Same code path as production ingest, so seeding also exercises it.
    CHUNK = 500
    for i in range(0, len(calls), CHUNK):
        await ingest.store(calls[i:i + CHUNK], broadcast=False)
        print(f"  {min(i + CHUNK, len(calls))}/{len(calls)}", end="\r", flush=True)

    async with db.pool().acquire() as conn:
        total = await conn.fetchval("SELECT count(*) FROM calls")
        newest = await conn.fetchval("SELECT max(started_at) FROM calls")
        contained = await conn.fetchval(
            "SELECT count(*) FILTER (WHERE handled_by='ai')::float / count(*) * 100 FROM calls"
        )

    print(f"\nseeded {len(calls)} calls  (table now {total})")
    print(f"newest call: {newest}")
    print(f"overall containment: {contained:.1f}%")

    await db.disconnect()


if __name__ == "__main__":
    asyncio.run(main())
