def _weighted(items: dict | list, rng: random.Random):
    if isinstance(items, dict):
        keys = list(items)
        weights = [v[0] if isinstance(v, tuple) else v for v in items.values()]
    else:
        keys = [k for k, _ in items]
        weights = [w for _, w in items]
    return rng.choices(keys, weights=weights, k=1)[0]


def _caller_hash(caller_id: int) -> str:
    return "sha256:" + hashlib.sha256(f"94{700000000 + caller_id}".encode()).hexdigest()[:32]


def _clamp(v: float, lo: float = -1.0, hi: float = 1.0) -> float:
    return max(lo, min(hi, v))


def _pick_language(district: str, rng: random.Random) -> tuple[str, list[str]]:
    p_si, p_ta, p_en = DISTRICTS[district][1]
    primary = rng.choices(["si", "ta", "en"], weights=[p_si, p_ta, p_en], k=1)[0]
    mix = [primary]
    # Code-switching is the norm in Sri Lanka — English terms inside a Sinhala
    # or Tamil call. Showing this explicitly is a differentiator.
    if primary != "en" and rng.random() < 0.34:
        mix.append("en")
    return primary, mix


def _make_call(
    started: datetime,
    rng: random.Random,
    caller_pool: int,
    *,
    force_intent: str | None = None,
    force_district: str | None = None,
    force_contained: bool | None = None,
    caller_id: int | None = None,
    followup_of: str | None = None,
) -> CallRecord:
    intent = force_intent or _weighted(INTENTS, rng)
    district = force_district or _weighted(DISTRICTS, rng)
    share, containment, median_dur, base_sent = INTENTS[intent]

    lang, lang_mix = _pick_language(district, rng)

    # Outcome ----------------------------------------------------------------
    if force_contained is None:
        r = rng.random()
        if r < 0.028:
            handled_by = "abandoned"
        elif r < containment * 0.97 + 0.028:
            handled_by = "ai"
        else:
            handled_by = "escalated" if rng.random() < 0.88 else "transferred_ivr"
    else:
        handled_by = "ai" if force_contained else "escalated"

    resolved = handled_by == "ai" and rng.random() < 0.94
    if handled_by == "escalated":
        resolved = False  # resolved by a human downstream; not by us

    escalation_reason = None
    if handled_by == "escalated":
        escalation_reason = _weighted(
            ESCALATION_BY_INTENT.get(intent, ESCALATION_DEFAULT), rng
        )

    # Duration ---------------------------------------------------------------
    duration = max(20, int(rng.gauss(median_dur, median_dur * 0.34)))
    if handled_by == "abandoned":
        duration = rng.randint(8, 45)
    elif handled_by == "escalated":
        duration = int(duration * rng.uniform(1.15, 1.6))
    ai_sec = duration if handled_by == "ai" else int(duration * rng.uniform(0.35, 0.7))
    queue_wait = rng.choices([0, 1, 2, 3, 5, 8], weights=[40, 25, 15, 10, 7, 3], k=1)[0]

    # Sentiment --------------------------------------------------------------
    s_start = _clamp(rng.gauss(base_sent, 0.22))
    if handled_by == "ai" and resolved:
        s_end = _clamp(s_start + rng.uniform(0.35, 0.95))
    elif handled_by == "escalated":
        s_end = _clamp(s_start + rng.uniform(-0.12, 0.22))
    elif handled_by == "abandoned":
        s_end = _clamp(s_start - rng.uniform(0.05, 0.35))
    else:
        s_end = _clamp(s_start + rng.uniform(0.0, 0.3))

    csat = int(round(_clamp((s_end + 1) / 2 * 4 + 1 + rng.gauss(0, 0.35), 1, 5)))

    # Churn ------------------------------------------------------------------
    churn_base = {"disconnection": 0.82, "complaint_followup": 0.42,
                  "broadband_fault": 0.16, "broadband_speed": 0.18,
                  "bill_inquiry": 0.07}.get(intent, 0.03)
    if not resolved:
        churn_base += 0.12
    if s_end < -0.3:
        churn_base += 0.15
    churn_risk = rng.random() < churn_base
    churn_signals = (
        rng.sample(CHURN_SIGNALS, k=rng.randint(1, 3)) if churn_risk else []
    )

    # Upsell -----------------------------------------------------------------
    upsell = None
    candidates = UPSELL_BY_INTENT.get(intent)
    if candidates and handled_by == "ai" and s_end > 0.1 and rng.random() < 0.19:
        upsell = rng.choice(candidates)

    # Knowledge gaps ---------------------------------------------------------
    unanswered: list[str] = []
    gap_chance = 0.14 if handled_by == "escalated" else 0.045
    if rng.random() < gap_chance:
        unanswered.append(_weighted(UNANSWERED_POOL, rng))

    # Actions ----------------------------------------------------------------
    action_names = ACTIONS_BY_INTENT.get(intent, ["lookup_account"])
    n_actions = len(action_names) if handled_by == "ai" else max(1, len(action_names) - 1)
    actions = []
    for i, name in enumerate(action_names[:n_actions]):
        ok = not (handled_by == "escalated" and i == n_actions - 1 and rng.random() < 0.3)
        ref = None
        if ok and name.startswith("raise_") :
            ref = f"FLT-{rng.randint(100000, 999999)}"
        actions.append(Action(action=name, status="ok" if ok else "failed", ref=ref))

    topics = list(TOPICS_BY_INTENT.get(intent, ["misc"]))
    rng.shuffle(topics)
    topics = topics[: rng.randint(1, min(3, len(topics)))]

    summary = rng.choice(SUMMARY_TEMPLATES.get(intent, ["Call handled."])).format(
        d=district, t=started.astimezone(TZ).strftime("%H:%M")
    )
    if followup_of:
        summary = "Repeat call — " + summary

    cid = caller_id if caller_id is not None else rng.randint(0, caller_pool - 1)

    return CallRecord(
        call_id=f"call_{uuid.uuid4().hex[:20]}",
        started_at=started,
        ended_at=started + timedelta(seconds=duration),
        duration_sec=duration,
        ai_handling_sec=ai_sec,
        queue_wait_sec=queue_wait,
        caller_hash=_caller_hash(cid),
        district=district,
        customer_segment=rng.choices(
            ["prepaid", "postpaid", "fixed", "enterprise"],
            weights=[52, 26, 18, 4], k=1
        )[0],
        channel="voice_inbound",
        affected_number=affected_number(intent, district, rng),
        intent=intent,
        sub_intent=None,
        topics=topics,
        language_primary=lang,
        language_mix=lang_mix,
        handled_by=handled_by,
        resolved=resolved,
        escalation_reason=escalation_reason,
        actions_taken=actions,
        sentiment_start=round(s_start, 3),
        sentiment_end=round(s_end, 3),
        csat_predicted=csat,
        interruptions=rng.choices([0, 1, 2, 3], weights=[62, 24, 10, 4], k=1)[0],
        silence_ratio=round(abs(rng.gauss(0.09, 0.05)), 3),
        churn_risk=churn_risk,
        churn_signals=churn_signals,
        upsell_opportunity=upsell,
        unanswered_questions=unanswered,
        summary=summary,
        enrichment_model="claude-opus-4-8",
        enrichment_confidence=round(rng.uniform(0.78, 0.99), 3),
    )


def _day_volume(day: datetime, per_day: int, rng: random.Random) -> int:
    weight = DOW_WEIGHTS[day.weekday()]
    return max(1, int(rng.gauss(per_day * weight, per_day * 0.07)))


def build(days: int, per_day: int, seed: int) -> list[CallRecord]:
    rng = random.Random(seed)
    now = datetime.now(TZ).replace(microsecond=0)
    caller_pool = max(500, per_day * days // 3)

    calls: list[CallRecord] = []

    # --- baseline traffic --------------------------------------------------
    for day_offset in range(days, 0, -1):
        day_start = (now - timedelta(days=day_offset)).replace(
            hour=0, minute=0, second=0, microsecond=0
        )
        for _ in range(_day_volume(day_start, per_day, rng)):
            hour = rng.choices(range(24), weights=HOUR_WEIGHTS, k=1)[0]
            started = day_start + timedelta(
                hours=hour, minutes=rng.randint(0, 59), seconds=rng.randint(0, 59)
            )
            if started >= now:
                continue
            calls.append(_make_call(started, rng, caller_pool))

    # Today so far, up to the current hour.
    today_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
    elapsed_weight = sum(HOUR_WEIGHTS[: now.hour + 1])
    today_target = int(per_day * DOW_WEIGHTS[now.weekday()] * elapsed_weight / sum(HOUR_WEIGHTS))
    for _ in range(today_target):
        hour = rng.choices(range(now.hour + 1), weights=HOUR_WEIGHTS[: now.hour + 1], k=1)[0]
        started = today_start + timedelta(
            hours=hour, minutes=rng.randint(0, 59), seconds=rng.randint(0, 59)
        )
        if started >= now:
            continue
        calls.append(_make_call(started, rng, caller_pool))

    # --- repeat callers ----------------------------------------------------
    # An unresolved call is the single best predictor of a call-back. Generating
    # these explicitly is what makes the first-contact-resolution proxy real
    # rather than an artefact of random caller collisions.
    followups: list[CallRecord] = []
    for c in calls:
        if c.resolved or c.handled_by == "abandoned":
            continue
        if rng.random() > 0.19:
            continue
        gap = timedelta(hours=rng.uniform(2.5, 22))
        started = c.started_at + gap
        if started >= now:
            continue
        caller_id = int(c.caller_hash[-6:], 16) % caller_pool  # irrelevant; overridden below
        f = _make_call(
            started, rng, caller_pool,
            force_intent="complaint_followup" if rng.random() < 0.45 else c.intent,
            force_district=c.district,
            followup_of=c.call_id,
        )
        f.caller_hash = c.caller_hash  # the whole point
        followups.append(f)
    calls.extend(followups)

    # --- planted incident: broadband outage in Gampaha ---------------------
    # Sits inside the detector's 2-hour window so the emerging-issue panel has
    # a real, defensible spike the moment the dashboard is opened.
    surge_calls = rng.randint(34, 46)
    for _ in range(surge_calls):
        started = now - timedelta(minutes=rng.uniform(3, 108))
        c = _make_call(
            started, rng, caller_pool,
            force_intent="broadband_fault",
            force_district="Gampaha",
            force_contained=rng.random() < 0.38,
        )
        c.topics = ["outage", "no_connection", "fibre"]
        c.sentiment_start = round(_clamp(rng.gauss(-0.72, 0.15)), 3)
        c.sentiment_end = round(_clamp(c.sentiment_start + rng.uniform(0.1, 0.6)), 3)
        c.summary = (
            "Customer in Gampaha reported broadband down. Multiple reports from "
            "the same area — suspected local outage. Fault ticket raised."
        )
        calls.append(c)

    # A second, smaller anomaly so the panel shows severity gradation rather
    # than a single all-caps alarm.
    for _ in range(rng.randint(9, 14)):
        started = now - timedelta(minutes=rng.uniform(5, 115))
        c = _make_call(
            started, rng, caller_pool,
            force_intent="peo_tv",
            force_district="Colombo",
            force_contained=rng.random() < 0.55,
        )
        c.topics = ["peo_tv", "channels"]
        calls.append(c)

    calls.sort(key=lambda c: c.started_at)
    return calls


